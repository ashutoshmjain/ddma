"""
test_mosaic_mux_integrity.py

Automated regression test suite verifying that:
1. DDMA canonical audio resolution strictly prefers raw continuous audio (.m4a)
   over mastered podcast (.mp3) to prevent sting-offset timeline drift.
2. The baseline draft video (clips/<ep>-<num>.mp4) generated by ddma cut + ddma mux-clip
   for export to Mosaic begins with the EXACT spoken words of the targeted clip hook,
   and contains ZERO overlap from preceding clips.
"""

import os
import sys
import json
import subprocess
import unittest
from pathlib import Path

# Add ddma to sys.path
DDMA_DIR = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(DDMA_DIR))
sys.path.insert(0, str(DDMA_DIR / "scratch"))

try:
    from run_curator import get_project_canonical_audio_path
except ImportError:
    get_project_canonical_audio_path = None


class TestMosaicMuxIntegrity(unittest.TestCase):

    def setUp(self):
        self.ddma_dir = DDMA_DIR
        self.project_dir = self.ddma_dir / "projects" / "episode_249"
        self.plan_path = self.project_dir / "plan.json"
        self.info_path = self.project_dir / "project_info.json"
        self.clips_dir = self.ddma_dir / "clips"
        self.clips_dir.mkdir(exist_ok=True)

    def test_01_canonical_audio_resolution_prioritizes_m4a(self):
        """Invariant: get_project_canonical_audio_path must always return .m4a over .mp3."""
        self.assertTrue(self.project_dir.exists(), f"Project dir {self.project_dir} must exist")
        self.assertTrue((self.project_dir / "249.m4a").exists(), "249.m4a raw audio must exist")
        self.assertTrue((self.project_dir / "249.mp3").exists(), "249.mp3 mastered audio must exist")

        canonical_path = get_project_canonical_audio_path(str(self.project_dir), "episode_249")
        self.assertTrue(
            canonical_path.endswith(".m4a"),
            f"Expected canonical audio to be .m4a, but got {canonical_path}"
        )

        # Verify project_info.json is also set to .m4a
        if self.info_path.exists():
            with open(self.info_path, "r", encoding="utf-8") as f:
                info = json.load(f)
            self.assertEqual(
                info.get("audio_filename"), "249.m4a",
                f"project_info.json must specify 249.m4a, found {info.get('audio_filename')}"
            )

    def test_02_mux_draft_body_audio_starts_with_exact_clip_words(self):
        """
        Invariant: The muxed draft body video sent to Mosaic must match the
        Whisper timestamps of the targeted clip hook, without speech bleeding from the previous clip.
        """
        # Read plan.json for Clip 5 (Quaternions)
        with open(self.plan_path, "r", encoding="utf-8") as f:
            plan = json.load(f)

        clip_5 = next((c for c in plan if int(c.get("num", -1)) == 5), None)
        self.assertIsNotNone(clip_5, "Clip 5 must exist in plan.json")

        audio_source = get_project_canonical_audio_path(str(self.project_dir), "episode_249")

        # 1. Run ddma.py cut
        cut_cmd = [
            sys.executable, "ddma.py", "cut",
            "--audio", audio_source,
            "--plan-file", str(self.plan_path),
            "--out-dir", str(self.clips_dir),
            "--num", "5"
        ]
        res_cut = subprocess.run(cut_cmd, capture_output=True, text=True, cwd=str(self.ddma_dir))
        self.assertEqual(res_cut.returncode, 0, f"ddma cut failed: {res_cut.stderr}")

        # 2. Run ddma.py mux-clip
        mux_cmd = [
            sys.executable, "ddma.py", "mux-clip",
            "--num", "5",
            "--plan-file", str(self.plan_path),
            "--out-dir", str(self.clips_dir)
        ]
        res_mux = subprocess.run(mux_cmd, capture_output=True, text=True, cwd=str(self.ddma_dir))
        self.assertEqual(res_mux.returncode, 0, f"ddma mux-clip failed: {res_mux.stderr}")

        draft_mp4 = self.clips_dir / "249-5.mp4"
        self.assertTrue(draft_mp4.exists(), f"Muxed draft video {draft_mp4} must exist")

        # 3. Extract first 8 seconds of audio and transcribe with Whisper
        temp_wav = self.ddma_dir / "scratch" / "test-env" / "test_clip5_first8s.wav"
        temp_wav.parent.mkdir(parents=True, exist_ok=True)

        extract_cmd = [
            "ffmpeg", "-y", "-i", str(draft_mp4),
            "-t", "8", "-ar", "16000", "-ac", "1",
            str(temp_wav)
        ]
        res_ext = subprocess.run(extract_cmd, capture_output=True, text=True)
        self.assertEqual(res_ext.returncode, 0, f"FFmpeg extraction failed: {res_ext.stderr}")

        from faster_whisper import WhisperModel
        model = WhisperModel("base", device="cpu", compute_type="int8")
        segments, _ = model.transcribe(str(temp_wav))
        spoken_text = " ".join([s.text for s in segments]).strip().lower()

        print(f"\n[Acoustic Verification] Spoken text in 249-5.mp4: '{spoken_text}'")

        # Negative assertion: MUST NOT contain ending speech from Clip 4
        self.assertNotIn("spatial changes", spoken_text, "Acoustic leak! Found Clip 4 concluding text in Clip 5.")
        self.assertNotIn("paradigm shift", spoken_text, "Acoustic leak! Found Clip 4 concluding text in Clip 5.")

        # Positive assertion: MUST contain Clip 5 hook keywords
        has_expected_hook = any(kw in spoken_text for kw in ["quaternion", "imaginary", "gears of reality", "5"])
        self.assertTrue(
            has_expected_hook,
            f"Clip 5 did not begin with expected hook keywords. Spoke: '{spoken_text}'"
        )

        # Cleanup test wav
        if temp_wav.exists():
            temp_wav.unlink()


if __name__ == "__main__":
    unittest.main()
